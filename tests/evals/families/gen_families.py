class _Dumper(yaml.SafeDumper):
    """Multi-line text (a seeded file, a skill) as a literal block, so the YAML reads like the file."""


_Dumper.add_representer(
    str,
    lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None),
)


def render(sc: dict) -> str:
    return HEADER + yaml.dump(sc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)



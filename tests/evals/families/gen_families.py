def _file(dom: D.Domain) -> str:
    return D.render(dom, comment_before=6, blank_after=(9, 19))


def _line_of(text: str, needle: str) -> int:
    for n, line in enumerate(text.split("\n"), 1):
        if needle in line and not line.startswith("#"):
            return n
    raise KeyError(needle)


def _seed(dom: D.Domain) -> dict:
    project, name = dom.path.split("/", 1)
    return {
        "files": [{"project": project, "name": name, "text": _file(dom)}],
        "skills": [{"id": D.SKILL_FIELDS[dom.name]["id"], "md": D.skill_md(dom)}],
    }


def _rows(dom: D.Domain, day: str, **kw) -> dict:
    project, name = dom.path.split("/", 1)
    return {"day_rows": {"project": project, "name": name, "day": day, **kw}}


def _fmt(v) -> str:
    s = format(v, "f")
    return s.rstrip("0").rstrip(".") if "." in s else s


def _sums(values: dict, cols) -> str:
    return ", ".join(f"{c} {_fmt(values[c])}" for c in cols)



"""Generate the three validation families for the refloop rig (ruling 41, design record section 9).

One shape per scenario, three vocabularies: the same twelve scenarios exist for food, expenses and
training, each seeded with the domain's two-day tracking file (a 15-row day with the owner's row
classes: rows with more fields than the header, an unknown left empty, a comment line, stray blank
lines) and the owner's own skill (3.4 to 4 KB, read through the skills index). Checks look at file
lines and replies only, never at a domain field by name.

Incident classes covered in every family:
  RC-08 add, correct, remove, move, undo, an identical re-log resolved by line   (log-three, correct,
        undo, move, relog)
  RC-16 a stated total equals the device sum; a partial total must name what it leaves out   (day-total, log-three)
  RC-19 an entry at 00:30 lands on the running day, with the year   (midnight)
  RC-13 a routine turn does not re-append   (routine)
  RC-09 no refusal of a correct row   (valid-odd)
  RC-01 a correction after three turns; RC-02 a correction after a cold start   (late-fix, cold-fix)
  a photo source kept in the transcript   (photo)

It also writes the expense and training families of the owner-regression battery
(tests/evals/owner_regressions/scenarios/lc-exp-*.json and lc-trn-*.json; the food family there is the
34 existing scenarios with their assertions on file lines): the same shapes as far as the lab driver
goes (no clock moves, no restart; RC-19 and the photo source are the refloop family's), plus an unknown
left empty and a question that is not an entry.

    python3 tests/evals/families/gen_families.py            # write both sets
    python3 tests/evals/families/gen_families.py --check    # exit 1 when a written file is stale
"""


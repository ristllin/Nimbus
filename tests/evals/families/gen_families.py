class _Dumper(yaml.SafeDumper):
    """Multi-line text (a seeded file, a skill) as a literal block, so the YAML reads like the file."""


_Dumper.add_representer(
    str,
    lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None),
)


def render(sc: dict) -> str:
    return HEADER + yaml.dump(sc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale, want = [], {}
    for dom in D.DOMAINS.values():
        for n, sc in enumerate(scenarios(dom), 1):
            want[OUT / dom.name / f"{n:02d}-{sc['id'].split('-', 1)[1]}.yaml"] = render(sc)
    have = set(OUT.glob("*/*.yaml")) if OUT.exists() else set()
    for path, text in want.items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for path in have - set(want):
        stale.append(path)
        if not args.check:
            path.unlink()
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(HERE.parents[2])}")
        return 1 if stale else 0
    print(f"wrote {len(stale)} of {len(want)} family scenarios")
    return 0


if __name__ == "__main__":
    sys.exit(main())

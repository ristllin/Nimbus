#!/usr/bin/env python3
"""Release gate: the shipped image's ELF - symbols and identity.

1. Symbols (CUM-167). The TFT firmware must link ZERO e-paper (GxEPD2) symbols: the
   ~14.5 KB internal-SRAM win from compiling the e-paper driver out must survive any
   display fix. It also asserts the color-TFT panel plumbing IS linked (a real defined
   symbol), so an empty/half-built ELF cannot pass silently.

2. Test-build crash switches. A shipped image must never link the test console's
   crash switches (TEST_ONLY_MARKERS): one that did could be made to crash on demand.
   This scan runs on every invocation, --identity-only included, so no release image
   can skip it.

3. Identity (crash forensics). A field core dump can only be decoded against the exact
   ELF that produced the image, so the release archives every variant's firmware.elf.
   With --bin, the gate proves the archived ELF IS that image: the build embeds the
   ELF's SHA-256 in the image's app descriptor (esp_app_desc_t.app_elf_sha256, image
   offset 0xB0), and the gate checks it equals sha256(firmware.elf). The device's core
   dump records the first hex digits of the same hash, so the archive is searchable by
   the "elf=" field of a crash line. --sha-out writes "<variant> <sha256>" for the
   release record.

4. Engine 2 links no engine-1 code (lane RB-I0, PRD section 10 L0). With --engine1-absent the
   gate reads an engine-2 ELF's defined symbols and fails on any symbol of
   tools/engine/e1_symbols.txt (the global, non-weak symbols the engine1_only objects define,
   generated by tools/engine/gen_e1_symbols.py). It runs alone (no e-paper, plumbing or
   crash-switch scan: the test-console e2 images carry the console by design; a release image is
   still checked by the normal invocation). An empty or missing list fails: the gate never passes
   vacuously.

Usage:
    pio run -e esp32s3            # build first
    python3 tools/release_gate/check_elf_symbols.py [--elf <path>]
    python3 tools/release_gate/check_elf_symbols.py --elf <elf> --bin <bin> [--identity-only]
        [--variant <name> --sha-out <file>]
    python3 tools/release_gate/check_elf_symbols.py --engine1-absent --elf .pio/build/<env>-e2/firmware.elf
Exit 0 = clean; exit 1 = e-paper linked, plumbing missing, a test-build crash switch
linked, ELF/bin mismatch, or a tool or file is unavailable. --identity-only skips the
e-paper and plumbing checks, never the crash-switch scan.
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import os
import struct
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_ELF = os.path.join(REPO, ".pio", "build", "esp32s3", "firmware.elf")
# The engine-1-only symbols an engine-2 ELF must not define (tools/engine/gen_e1_symbols.py).
E1_SYMBOLS = os.path.join(REPO, "tools", "engine", "e1_symbols.txt")

# Symbols that must NOT appear (the e-paper footprint).
EPAPER_MARKERS = ("GxEPD2", "SSD1680")
# A symbol that MUST appear (proves the color-TFT driver is actually linked).
REQUIRED_TFT = "solide11display_tft5begin"  # mangled solide::display_tft::begin
# Test-build crash switches (the console's PANIC ... arm=turn): a shipped image that
# linked them could be made to crash on demand. Source guard: test_panic_guard.py.
TEST_ONLY_MARKERS = (
    "armTurnPanic",
    "testPanicPoint",
    "parsePanicArm",
    "panicArmFires",
    "firePanic",
    "faultNullStore",
    "faultDeepen",
    # The console's CLOCK skew (src/test_console.cpp): a shipped image that linked it could
    # have its wall clock moved over serial. Every clockSkew* function carries the marker.
    "clockSkew",
    # Lane RB-M2's bench timing (src/sys/link_time.h, the console's LINKX, CARDTIME and LOGMS):
    # test builds only. Every symbol it defines carries the marker.
    "linkTime",
)

# ESP-IDF app image layout (esp_image_format.h / esp_app_desc.h): a 24-byte image
# header, an 8-byte first-segment header, then esp_app_desc_t, whose app_elf_sha256
# field sits 0x90 into the descriptor.
IMAGE_MAGIC = 0xE9
APP_DESC_OFFSET = 0x20
APP_DESC_MAGIC = 0xABCD5432
ELF_SHA_OFFSET = 0xB0
ELF_SHA_LEN = 32


def find_nm() -> "str | None":
    hits = glob.glob(os.path.expanduser("~/.platformio/packages/toolchain-*/bin/xtensa-esp32s3-elf-nm"))
    return hits[0] if hits else None


def read_symbols(nm: str, elf: str) -> str:
    out = subprocess.run([nm, elf], capture_output=True, text=True)
    return out.stdout


def read_e1_symbols(path: str = E1_SYMBOLS) -> "list[str]":
    """The listed names (one per line, '#' comments)."""
    with open(path, encoding="utf-8") as f:
        return [ln.split("#", 1)[0].strip() for ln in f if ln.split("#", 1)[0].strip()]


def defined_names(nm_text: str) -> "set[str]":
    """Names `nm --defined-only` lists (any type: a local or weak copy of an engine-1 symbol is
    engine-1 code too)."""
    out = set()
    for line in nm_text.splitlines():
        bits = line.split()
        if len(bits) >= 3:
            out.add(bits[-1])
    return out


def check_engine1_absent(nm_text: str, listed: "list[str]") -> "tuple[bool, list[str]]":
    """(ok, messages): no listed engine-1 symbol is defined in the image."""
    if not listed:
        return False, ["the engine-1 symbol list is empty: regenerate tools/engine/e1_symbols.txt"]
    names = defined_names(nm_text)
    if not names:
        return False, ["the ELF defines no symbol: not a firmware image"]
    hits = sorted(set(listed) & names)
    if hits:
        shown = ", ".join(hits[:12]) + (f" (+{len(hits) - 12} more)" if len(hits) > 12 else "")
        return False, [f"{len(hits)} engine-1 symbol(s) defined in an engine-2 image: {shown}"]
    return True, [f"none of the {len(listed)} engine-1 symbols is defined ({len(names)} symbols read)"]


def run_engine1_absent(elf_path: str, list_path: str) -> bool:
    nm = find_nm()
    if not nm:
        print("[gate:elf-symbols] FAIL: xtensa-esp32s3-elf-nm not found")
        return False
    try:
        listed = read_e1_symbols(list_path)
    except OSError as e:
        print(f"[gate:elf-symbols] FAIL: {list_path}: {e}")
        return False
    out = subprocess.run([nm, "--defined-only", elf_path], capture_output=True, text=True)
    ok, msgs = check_engine1_absent(out.stdout, listed)
    for m in msgs:
        print(f"[gate:elf-symbols] {'ok' if ok else '!!'} {m}")
    return ok


def check_test_only(symbols: str) -> "tuple[bool, str]":
    """(ok, message): no test-build crash switch is linked. Runs on every image."""
    test_only = [m for m in TEST_ONLY_MARKERS if m in symbols]
    if test_only:
        return False, f"test-build crash switches linked into a shipped image: {test_only}"
    return True, "no test-build crash switches"


def check(symbols: str) -> "tuple[bool, list[str]]":
    """(ok, messages)."""
    msgs = []
    ok = True
    epaper = [m for m in EPAPER_MARKERS if m.lower() in symbols.lower()]
    if epaper:
        ok = False
        msgs.append(f"e-paper symbols present in the TFT image: {epaper} (the 14.5 KB win regressed)")
    else:
        msgs.append("no GxEPD2 / e-paper symbols (size win intact)")
    test_only_ok, test_only_msg = check_test_only(symbols)
    ok = ok and test_only_ok
    msgs.append(test_only_msg)
    if REQUIRED_TFT not in symbols:
        ok = False
        msgs.append(f"missing color-TFT plumbing symbol ({REQUIRED_TFT}) - ELF may be empty/half-built")
    else:
        msgs.append("color-TFT panel plumbing is linked")
    return ok, msgs


def embedded_elf_sha(image: bytes) -> "str | None":
    """The app_elf_sha256 the build embedded in an app image, or None if it is not one."""
    if len(image) < ELF_SHA_OFFSET + ELF_SHA_LEN or image[0] != IMAGE_MAGIC:
        return None
    (magic,) = struct.unpack_from("<I", image, APP_DESC_OFFSET)
    if magic != APP_DESC_MAGIC:
        return None
    return image[ELF_SHA_OFFSET : ELF_SHA_OFFSET + ELF_SHA_LEN].hex()


def check_identity(elf_bytes: bytes, image: bytes) -> "tuple[bool, str, str]":
    """(ok, message, elf_sha256): the image's embedded ELF hash equals sha256(elf)."""
    elf_sha = hashlib.sha256(elf_bytes).hexdigest()
    embedded = embedded_elf_sha(image)
    if embedded is None:
        return False, "the --bin file is not an ESP-IDF app image (no app descriptor)", elf_sha
    if embedded != elf_sha:
        return False, f"ELF does not match the image: image says {embedded[:16]}.., ELF is {elf_sha[:16]}..", elf_sha
    return True, f"ELF matches the image (app_elf_sha256 {elf_sha[:16]}..)", elf_sha


def run_symbols(elf_path: str, full: bool = True) -> bool:
    """The symbol checks: all of them, or (full=False) only the crash-switch scan."""
    nm = find_nm()
    if not nm:
        print(
            "[gate:elf-symbols] FAIL: xtensa-esp32s3-elf-nm not found (build the firmware once to fetch the toolchain)"
        )
        return False
    symbols = read_symbols(nm, elf_path)
    if full:
        ok, msgs = check(symbols)
    else:
        ok, msg = check_test_only(symbols)
        msgs = [msg]
    for m in msgs:
        print(f"[gate:elf-symbols] {'ok' if ok else '!!'} {m}")
    return ok


def run_identity(elf_path: str, bin_path: str, variant: str, sha_out: "str | None") -> bool:
    if not os.path.exists(bin_path):
        print(f"[gate:elf-symbols] FAIL: image not found at {bin_path}")
        return False
    with open(elf_path, "rb") as f:
        elf_bytes = f.read()
    with open(bin_path, "rb") as f:
        image = f.read()
    ok, msg, sha = check_identity(elf_bytes, image)
    print(f"[gate:elf-symbols] {'ok' if ok else '!!'} {msg}")
    if ok and sha_out:
        with open(sha_out, "a") as f:
            f.write(f"{variant or os.path.basename(bin_path)} {sha}\n")
    return ok


def main(argv: "list[str] | None" = None) -> int:
    ap = argparse.ArgumentParser(description="Release gate: ELF symbols and image identity")
    ap.add_argument("--elf", default=DEFAULT_ELF, help="path to the built firmware.elf")
    ap.add_argument("--bin", help="the matching firmware.bin: assert its embedded ELF hash")
    ap.add_argument(
        "--identity-only",
        action="store_true",
        help="skip the e-paper and TFT plumbing checks (the crash-switch scan always runs)",
    )
    ap.add_argument("--variant", default="", help="variant name for --sha-out")
    ap.add_argument("--sha-out", help="append '<variant> <app_elf_sha256>' to this file")
    ap.add_argument(
        "--engine1-absent",
        action="store_true",
        help="engine-2 image: fail on any symbol of tools/engine/e1_symbols.txt (runs alone, RB-I0)",
    )
    ap.add_argument("--e1-symbols", default=E1_SYMBOLS, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if args.engine1_absent:
        if not os.path.exists(args.elf):
            print(f"[gate:elf-symbols] FAIL: ELF not found at {args.elf}")
            return 1
        ok = run_engine1_absent(args.elf, args.e1_symbols)
        print(f"[gate:elf-symbols] {'PASS' if ok else 'FAIL'} engine 2 links no engine-1 symbol: {args.elf}")
        return 0 if ok else 1
    if args.identity_only and not args.bin:
        ap.error("--identity-only needs --bin (it is the identity check)")  # a gate never passes vacuously

    if not os.path.exists(args.elf):
        print(f"[gate:elf-symbols] FAIL: ELF not found at {args.elf} - run `pio run -e esp32s3` first")
        return 1
    ok = run_symbols(args.elf, full=not args.identity_only)
    if args.bin:
        ok = run_identity(args.elf, args.bin, args.variant, args.sha_out) and ok
    print(f"[gate:elf-symbols] {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())

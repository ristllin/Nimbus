#!/usr/bin/env python3
"""Generate the host test's copy of the router refusal contract, and engine 2's reasons.

tools/router_contract/router-refusal-contract.md is a verbatim copy of the cloud repo's
docs-internal/router-refusal-contract.md. Copy a newer one over it, run this, and
test_router_refusal_contract then fails until lib/core's table agrees with it.

A second output, lib/core/include/nimbus/orch/router_reasons_e2.h, is engine 2's table, from
router-refusal-contract-cloud.md (the cloud repo's current contract, copied verbatim). Engine 1's
router_refusals.h is hand-kept and is not regenerated (ROUTER-DESIGN.md section 2, C12).

Usage: python3 tools/router_contract/gen_contract_header.py [--check]
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/router_contract/router-refusal-contract.md"
OUT = ROOT / "test/test_router_refusal_contract/contract_rows.h"
SRC_E2 = ROOT / "tools/router_contract/router-refusal-contract-cloud.md"
OUT_E2 = ROOT / "lib/core/include/nimbus/orch/router_reasons_e2.h"
ACTIONS = {
    "fix_request": "FixRequest",
    "retry_later": "RetryLater",
    "retry_capped": "RetryCapped",
    "fail_over": "FailOver",
    "park_billing": "ParkBilling",
    "park_auth": "ParkAuth",
}
ROW = re.compile(r"^\| `([a-z_]+)`\s*\| (\d+)\s*\| (yes|no)\s*\| `([a-z_]+)`\s*\|")


def rows(text):
    return [m.groups() for m in map(ROW.match, text.splitlines()) if m]


def bodies(text):
    out = []
    for block in re.findall(r"```json\n(.*?)```", text, re.S):
        body = json.loads(block)
        out.append((body["reason"], json.dumps(body, separators=(",", ":"))))
    return out


def cxx(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    text = SRC.read_text()
    lines = [
        "#pragma once",
        "// GENERATED by tools/router_contract/gen_contract_header.py from the cloud repo's",
        "// router refusal contract. Do not edit by hand.",
        "struct ContractRow {",
        "  const char* reason;",
        "  int http;",
        "  bool retryable;",
        "  const char* action;",
        "};",
        "static const ContractRow kContractRows[] = {",
    ]
    for reason, http, retry, action in rows(text):
        lines.append(f'    {{"{reason}", {http}, {"true" if retry == "yes" else "false"}, "{action}"}},')
    lines += [
        "};",
        "struct ContractBody {",
        "  const char* reason;",
        "  const char* json;",
        "};",
        "static const ContractBody kContractBodies[] = {",
    ]
    for reason, body in bodies(text):
        lines.append(f"    {{{cxx(reason)}, {cxx(body)}}},")
    lines += ["};", ""]
    return "\n".join(lines)


def render_e2():
    lines = [
        "#pragma once",
        "// GENERATED by tools/router_contract/gen_contract_header.py from",
        "// tools/router_contract/router-refusal-contract-cloud.md (the cloud repo's contract).",
        "// Do not edit by hand. Engine 2 only: engine 1 reads router_refusals.h.",
        '#include "nimbus/orch/router_refusals.h"',
        "",
        "namespace nimbus {",
        "namespace orch {",
        "",
        "inline constexpr RouterReasonRow kRouterReasonsE2[] = {",
    ]
    for reason, http, retry, action in rows(SRC_E2.read_text()):
        lines.append(
            f'    {{"{reason}", {http}, {"true" if retry == "yes" else "false"}, RouterAction::{ACTIONS[action]}}},'
        )
    lines += ["};", "", "}  // namespace orch", "}  // namespace nimbus", ""]
    return "\n".join(lines)


def main():
    outs = [(OUT, render()), (OUT_E2, render_e2())]
    if "--check" in sys.argv:
        for out, want in outs:
            if out.read_text() != want:
                sys.exit(f"{out.name} is stale: run tools/router_contract/gen_contract_header.py")
        return
    for out, want in outs:
        out.write_text(want)


if __name__ == "__main__":
    main()

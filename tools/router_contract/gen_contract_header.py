#!/usr/bin/env python3
"""Generate the host test's copy of the router refusal contract.

tools/router_contract/router-refusal-contract.md is a verbatim copy of the cloud repo's
docs-internal/router-refusal-contract.md. Copy a newer one over it, run this, and
test_router_refusal_contract then fails until lib/core's table agrees with it.

Usage: python3 tools/router_contract/gen_contract_header.py [--check]
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/router_contract/router-refusal-contract.md"
OUT = ROOT / "test/test_router_refusal_contract/contract_rows.h"
ROW = re.compile(r"^\| `([a-z_]+)`\s*\| (\d+)\s*\| (yes|no)\s*\| `([a-z_]+)`\s*\|")


def rows(text):
    return [m.groups() for m in map(ROW.match, text.splitlines()) if m]


def bodies(text):
    out = []
    for block in re.findall(r"```json\n(.*?)```", text, re.S):
        body = json.loads(block)
        out.append((body["reason"], json.dumps(body, separators=(",", ":"))))
    return out


def cxx(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    text = SRC.read_text()
    lines = [
        "#pragma once",
        "// GENERATED by tools/router_contract/gen_contract_header.py from the cloud repo's",
        "// router refusal contract. Do not edit by hand.",
        "struct ContractRow {",
        "  const char* reason;",
        "  int http;",
        "  bool retryable;",
        "  const char* action;",
        "};",
        "static const ContractRow kContractRows[] = {",
    ]
    for reason, http, retry, action in rows(text):
        lines.append(f'    {{"{reason}", {http}, {"true" if retry == "yes" else "false"}, "{action}"}},')
    lines += [
        "};",
        "struct ContractBody {",
        "  const char* reason;",
        "  const char* json;",
        "};",
        "static const ContractBody kContractBodies[] = {",
    ]
    for reason, body in bodies(text):
        lines.append(f"    {{{cxx(reason)}, {cxx(body)}}},")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    want = render()
    if "--check" in sys.argv:
        if OUT.read_text() != want:
            sys.exit("contract_rows.h is stale: run tools/router_contract/gen_contract_header.py")
        return
    OUT.write_text(want)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate tools/engine/e1_symbols.txt: the symbols only the old engine (engine 1) defines (lane RB-I0).

An engine-2 device image must link no engine-1 code (PRD section 10). tools/engine/engine1_only.txt
lists the engine-1 sources and tools/engine_filter.py keeps them out of an engine-2 build, so their
objects never load (check_engine_filter.py reads the map). This list closes the other gap: an
engine-1 function moved into, or inlined from a header into, a source both engines compile. It is
every symbol an engine1_only object defines with GLOBAL, non-weak binding (nm types T, D, B, R and
the GNU unique u): such a symbol has exactly one strong definition in a link, so finding it in an
engine-2 ELF means engine-1 code is there. Weak and COMDAT symbols (inline functions, template
instantiations, vtables of shared classes: nm W, V) and local ones are left out: both engines may
define those legitimately. The engine seam's interface is left out too: a call of
src/agent/engine_api.h or engine_tools.h is defined by both seams by design (orchestrator_e1.cpp and
orchestrator_plain.cpp, tools_e1.cpp and tools_plain.cpp), so every symbol the engine-2 device
sources (the src/ entries of engine2_only.txt) define in the twin <env>-e2 build is subtracted.

The objects come from the engine-1 builds of this tree (.pio/build/<env>), every env given, so
the NIMBUS_TEST console's engine-1 symbols are listed too. The check is
`tools/release_gate/check_elf_symbols.py --engine1-absent --elf <e2 firmware.elf>`.

Usage (after `pio run -e esp32s3-cyd -e test-cyd -e esp32s3-cyd-e2 -e test-cyd-e2`):
    python3 tools/engine/gen_e1_symbols.py [--env esp32s3-cyd --env test-cyd] [--out PATH]
    python3 tools/engine/gen_e1_symbols.py --check     # exit 1 when the committed list differs
"""

from __future__ import annotations

import argparse
import glob
import os
import subprocess
import sys
from typing import Dict, Iterable, List, Optional, Sequence, Set

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.dirname(HERE))

import engine_filter  # noqa: E402

LIST = os.path.join(HERE, "e1_symbols.txt")
DEFAULT_ENVS = ("esp32s3-cyd", "test-cyd")
STRONG_TYPES = set("TDBRu")
HEADER = """# Symbols only the old engine (engine 1) defines: GENERATED by tools/engine/gen_e1_symbols.py from the
# objects of tools/engine/engine1_only.txt in the engine-1 builds named below; never edit by hand.
# check_elf_symbols.py --engine1-absent fails when an engine-2 ELF defines any of them.
# One mangled name per line, then '#' and the engine1_only source that defines it.
"""


class GenError(Exception):
    pass


def find_nm() -> str:
    hits = sorted(glob.glob(os.path.expanduser("~/.platformio/packages/toolchain-*/bin/xtensa-esp32s3-elf-nm")))
    if not hits:
        raise GenError("xtensa-esp32s3-elf-nm not found (build a device env once to fetch the toolchain)")
    return hits[0]


def object_for(build: str, rel: str) -> Optional[str]:
    """The object PlatformIO built for repo source `rel` in env build dir `build`, or None."""
    if rel.startswith("src/"):
        path = os.path.join(build, rel + ".o")
        return path if os.path.isfile(path) else None
    parts = rel.split("/")
    if len(parts) >= 4 and parts[0] == "lib" and parts[2] == "src":
        rest = "/".join(parts[3:])
        hits = sorted(glob.glob(os.path.join(build, "lib*", parts[1], rest + ".o")))
        return hits[0] if hits else None
    return None


def strong_globals(nm_text: str) -> Set[str]:
    """Names of the symbols `nm --defined-only` lists with a global, non-weak type."""
    out = set()
    for line in nm_text.splitlines():
        bits = line.split()
        if len(bits) >= 3 and bits[-2] in STRONG_TYPES:
            out.add(bits[-1])
    return out


def nm_strong(nm: str, obj: str) -> Set[str]:
    return strong_globals(
        subprocess.run([nm, "--defined-only", obj], capture_output=True, text=True, check=True).stdout
    )


def seam_interface(root: str, env: str, nm: str) -> Set[str]:
    """The symbols the engine-2 device sources define in the twin env `<env>-e2` (the seam's calls)."""
    build = os.path.join(root, ".pio", "build", env + "-e2")
    if not os.path.isdir(build):
        raise GenError(f"env {env}-e2 is not built (pio run -e {env}-e2): the seam interface is read from it")
    e2 = engine_filter.load_list(os.path.join(root, engine_filter.LIST_DIR, engine_filter.DROP_LIST[1]))
    out: Set[str] = set()
    for rel in e2:
        if rel.startswith("src/"):
            obj = object_for(build, rel)
            if obj is None:
                raise GenError(f"env {env}-e2: no object for {rel}")
            out |= nm_strong(nm, obj)
    return out


def collect(root: str, envs: Iterable[str], nm: str) -> Dict[str, str]:
    """symbol -> the engine1_only source that defines it, over every env's objects, less the seam interface."""
    sources = engine_filter.load_list(os.path.join(root, engine_filter.LIST_DIR, engine_filter.DROP_LIST[2]))
    found: Dict[str, str] = {}
    interface: Set[str] = set()
    for env in envs:
        interface |= seam_interface(root, env, nm)
        build = os.path.join(root, ".pio", "build", env)
        if not os.path.isdir(build):
            raise GenError(f"env {env} is not built (pio run -e {env})")
        if _engine_of(root, env) != 1:
            raise GenError(f"env {env} does not build engine 1")
        missing = []
        for rel in sources:
            obj = object_for(build, rel)
            if obj is None:
                missing.append(rel)
                continue
            for sym in nm_strong(nm, obj):
                found.setdefault(sym, rel)
        if missing:
            raise GenError(f"env {env}: no object for " + ", ".join(missing))
    return {sym: rel for sym, rel in found.items() if sym not in interface}


def _engine_of(root: str, env: str) -> int:
    sys.path.insert(0, os.path.join(HERE, "..", "release_gate"))
    import check_engine_filter  # noqa: E402

    return check_engine_filter.PioIni(os.path.join(root, "platformio.ini")).engine(env)


def render(found: Dict[str, str], envs: Sequence[str]) -> str:
    lines = [HEADER.rstrip("\n"), f"# envs: {' '.join(envs)}; {len(found)} symbols", ""]
    for sym in sorted(found):
        lines.append(f"{sym}  # {found[sym]}")
    return "\n".join(lines) + "\n"


def read_list(path: str = LIST) -> List[str]:
    with open(path, encoding="utf-8") as fh:
        return [ln.split("#", 1)[0].strip() for ln in fh if ln.split("#", 1)[0].strip()]


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="generate tools/engine/e1_symbols.txt")
    ap.add_argument("--root", default=REPO)
    ap.add_argument("--env", action="append", help="an engine-1 env whose objects to read (repeatable)")
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed list differs")
    args = ap.parse_args(argv)
    envs = args.env or list(DEFAULT_ENVS)
    out = args.out or os.path.join(args.root, "tools", "engine", "e1_symbols.txt")
    try:
        text = render(collect(args.root, envs, find_nm()), envs)
    except (GenError, OSError, subprocess.CalledProcessError) as e:
        print(f"[e1-symbols] FAIL: {e}")
        return 1
    if args.check:
        with open(out, encoding="utf-8") as fh:
            same = fh.read() == text
        print(f"[e1-symbols] {'GREEN: the list is current' if same else 'RED: regenerate tools/engine/e1_symbols.txt'}")
        return 0 if same else 1
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"[e1-symbols] wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
